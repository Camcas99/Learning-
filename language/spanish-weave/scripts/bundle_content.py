#!/usr/bin/env python3
"""Writes extension/src/content.bundle.js: content.js and the modules it imports as one classic script.

Content scripts can't be ES modules. Loading content.js with import() needs it and its imports listed in the
manifest's web_accessible_resources, and then any website can fetch them at the extension's fixed ID and learn that
Spanish Weave is installed. use_dynamic_url doesn't fix that: Chromium resolves the module's own imports against the
fixed ID and refuses them. So the extension ships one bundle and lists nothing as web accessible. Each module keeps
its own scope (a function returning its exports), in import order, so the bundle runs exactly like the modules do;
the tests import the modules themselves and run the bundle in a page.
Usage: python3 scripts/bundle_content.py [--check]   (--check: fail if the bundle is out of date)
"""
import argparse
from pathlib import Path
import re
import sys

SRC = Path(__file__).resolve().parent.parent / 'extension' / 'src'
ENTRY = 'content.js'
OUT = SRC / 'content.bundle.js'
IMPORT = re.compile(r"^import\s*\{([^}]*)\}\s*from\s*'\./([\w-]+\.js)';[ \t]*\n", re.M)
EXPORT = re.compile(r'^export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)', re.M)


def scope(name):
    return 'm_' + re.sub(r'\W', '_', name[:-3])


def module(name, seen, order):
    """Appends name and the modules it imports to order, imports first."""
    if name in seen:
        return
    seen.add(name)
    text = (SRC / name).read_text(encoding='utf-8')
    if re.search(r'^\s*(?:import\b(?!\()|export\s+(?:default|\{|\*))', IMPORT.sub('', text), re.M) or 'import.meta' in text:
        sys.exit(f'{name}: only single-line named imports from ./x.js and named exports can be bundled')
    for _, dep in IMPORT.findall(text):
        module(dep, seen, order)
    order.append(name)


def body(name):
    text = (SRC / name).read_text(encoding='utf-8')
    names = lambda spec: ', '.join(part.strip().replace(' as ', ': ') for part in spec.split(',') if part.strip())
    text = IMPORT.sub(lambda m: f'const {{ {names(m.group(1))} }} = {scope(m.group(2))};\n', text)
    exports = EXPORT.findall(text)
    text = re.sub(r'^export\s+', '', text, flags=re.M)
    return text.rstrip('\n') + (f'\nreturn {{ {", ".join(exports)} }};' if exports else '')


def bundle():
    order = []
    module(ENTRY, set(), order)
    parts = ['// Generated by scripts/bundle_content.py from src/content.js and the modules it imports; edit those and '
             'rerun it.\n'
             "// One classic content script, so the extension lists no web-accessible files a website could probe.\n"
             '(() => {\n'
             '// The popup injects it into an open tab that may already run it; import() ran a module once, so must this.\n'
             'if (globalThis.spanishWeaveLoaded) return;\n'
             'globalThis.spanishWeaveLoaded = true;\n']
    for name in order:
        parts.append(f"// ---- {name}\n" + (f'const {scope(name)} = ' if name != ENTRY else '')
                     + "(() => {\n'use strict';\n" + body(name) + '\n})();\n')
    return ''.join(parts) + '})();\n'


def main(argv):
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    text = bundle()
    if args.check:
        current = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
        if current != text:
            print(f'{OUT} is out of date: run python3 scripts/bundle_content.py')
            return 1
        print('content bundle is current')
        return 0
    OUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
